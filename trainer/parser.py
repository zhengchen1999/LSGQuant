import argparse


def wan_parser():
    parser = argparse.ArgumentParser(description="Simple example of a training script.")
    parser.add_argument("--dataset_base_path", type=str, default="", help="Base path of the dataset.")
    parser.add_argument("--dataset_metadata_path", type=str, help="Path to the metadata file of the dataset.")
    parser.add_argument('--batch_size', type=int, default=1, help="Batch size for training.")
    parser.add_argument('--iterations', type=int, default=10000, help="Number of training iterations.")
    parser.add_argument("--height", type=int, default=None, help="Height of images or videos. Leave `height` and `width` empty to enable dynamic resolution.")
    parser.add_argument("--width", type=int, default=None, help="Width of images or videos. Leave `height` and `width` empty to enable dynamic resolution.")
    parser.add_argument("--num_frames", type=int, default=81, help="Number of frames per video. Frames are sampled from the video prefix.")
    parser.add_argument("--data_file_keys", type=str, default="image,video", help="Data file keys in the metadata. Comma-separated.")
    parser.add_argument("--dataset_repeat", type=int, default=1, help="Number of times to repeat the dataset per epoch.")
    parser.add_argument("--model_paths", type=str, default=None, help="Paths to load models. In JSON format.")
    parser.add_argument("--model_id_with_origin_paths", type=str, default=None, help="Model ID with origin paths, e.g., Wan-AI/Wan2.1-T2V-1.3B:diffusion_pytorch_model*.safetensors. Comma-separated.")
    parser.add_argument("--learning_rate", type=float, default=1e-4, help="Learning rate.")
    parser.add_argument("--num_epochs", type=int, default=1, help="Number of epochs.")
    parser.add_argument("--output_path", type=str, default="./models", help="Output save path.")
    parser.add_argument("--remove_prefix_in_ckpt", type=str, default="pipe.dit.", help="Remove prefix in ckpt.")
    parser.add_argument("--trainable_models", type=str, default=None, help="Models to train, e.g., dit, vae, text_encoder.")
    parser.add_argument("--extra_inputs", default=None, help="Additional model inputs, comma-separated.")
    parser.add_argument("--use_gradient_checkpointing_offload", default=False, action="store_true", help="Whether to offload gradient checkpointing to CPU memory.")
    parser.add_argument("--record_step", type=int, default=500, help="Record every this many steps.")
    parser.add_argument('--degradation_config', type=str, default='datasets/degradation.yaml')
    parser.add_argument('--prompt_cache', type=str, default='prompt_cache')
    parser.add_argument('--val_path', type=str)
    parser.add_argument('--eval_metrics', type=str)
    parser.add_argument('--sr_step', type=int)
    parser.add_argument('--debug', action='store_true')
    parser.add_argument('--video_loss', action='store_true')
    parser.add_argument('--scheduler_type', type=str, choices=['constant_warm_up', 'decay_warm_up', 'cosine_decay_warm_up'])
    parser.add_argument('--aux_loss', type=str, choices=['lpips', 'dists'])
    parser.add_argument('--ckpt_path', type=str, help="Checkpoint path, used for evaluation, or following stage training")
    parser.add_argument('--upscale', type=int, default=4)
    parser.add_argument('--temp_loss', default=None, type=str, choices=["warp_loss", "frame_diff_loss"])
    parser.add_argument('--flow_path', type=str, default="eval_metric/RAFT/models/raft-things.pth")
    parser.add_argument('--temp_weight', type=float, default=1)
    parser.add_argument('--latent_loss', action='store_true')
    parser.add_argument('--start_idx', type=int, default=1, help="Used for data generation.")

    parser.add_argument('--tiled', action='store_true')
    parser.add_argument('--tile_size', type=int, nargs=2, default=(34, 34))
    parser.add_argument('--tile_stride', type=int, nargs=2, default=(18, 16))

    return parser
